/** 预编译的字符类正则（CJK 字符在字符类里无需转义）。 */
const T2S_PATTERN = new RegExp(`[${Object.keys(T2S_TABLE).join('')}]`, 'g');

/** 映射表的字符条数（自检用）。 */
export const T2S_SIZE = Object.keys(T2S_TABLE).length;

/**
 * 把文本中的繁体高频字替换成简体（一对一，不改变其它语义）。
 *
 * @param text 输入文本（任意长度）
 * @return 简体化后的文本
 */
export function toSimplified(text: string): string {
  if (text.length === 0) {
    return text;
  }
  return text.replace(T2S_PATTERN, (char) => T2S_TABLE[char] ?? char);
}
